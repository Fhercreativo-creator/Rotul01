// Normalizar los recursos locales para las páginas de distintas profundidades.
(() => {
  const root = document.body.dataset.root || '';
  const resolve = value => {
    if (typeof value === 'string') return value.startsWith('assets/') ? root + value : value;
    if (Array.isArray(value)) return value.map(resolve);
    if (value && typeof value === 'object') return Object.fromEntries(Object.entries(value).map(([key, item]) => [key, resolve(item)]));
    return value;
  };
  window.ROTUL = resolve(window.ROTUL);
})();


