(() => {
  'use strict';
  const root = document.querySelector('[data-feature-player]');
  if (!root) return;
  const video = root.querySelector('video');
  const controls = root.querySelector('.film-controls');
  const playButton = root.querySelector('[data-film-play]');
  const soundButton = root.querySelector('[data-film-sound]');
  const fullscreenButton = root.querySelector('[data-film-fullscreen]');
  const seek = root.querySelector('[data-film-seek]');
  const current = root.querySelector('[data-film-current]');
  const duration = root.querySelector('[data-film-duration]');
  const status = root.querySelector('[data-film-status]');
  const reduced = matchMedia('(prefers-reduced-motion: reduce)');
  let visible = false, manualPause = false, failed = false;
  const time = seconds => {
    const value = Math.max(0, Math.floor(Number(seconds) || 0));
    return `${String(Math.floor(value / 60)).padStart(2, '0')}:${String(value % 60).padStart(2, '0')}`;
  };
  function sync() {
    root.classList.toggle('film-is-playing', !video.paused);
    root.classList.toggle('film-has-sound', !video.muted);
    playButton.setAttribute('aria-label', video.paused ? 'Reproducir video' : 'Pausar video');
    soundButton.setAttribute('aria-label', video.muted ? 'Activar sonido' : 'Silenciar video');
    soundButton.setAttribute('aria-pressed', String(!video.muted));
  }
  function progress() {
    current.textContent = time(video.currentTime);
    if (!Number.isFinite(video.duration) || video.duration <= 0) return;
    duration.textContent = time(video.duration);
    seek.value = String(video.currentTime / video.duration * 100);
    seek.style.setProperty('--film-progress', `${seek.value}%`);
    seek.setAttribute('aria-valuetext', `${time(video.currentTime)} de ${time(video.duration)}`);
  }
  async function play() {
    if (failed || !video.paused) return;
    try { await video.play(); } catch { sync(); }
  }
  function automatic() {
    if (!visible || document.hidden || manualPause || reduced.matches || navigator.connection?.saveData) video.pause();
    else play();
  }
  video.muted = true;
  video.defaultMuted = true;
  video.loop = true;
  video.controls = false;
  controls.hidden = false;
  root.classList.add('film-enhanced');
  playButton.addEventListener('click', () => {
    if (video.paused) { manualPause = false; play(); }
    else { manualPause = true; video.pause(); }
  });
  soundButton.addEventListener('click', () => { video.muted = !video.muted; sync(); });
  seek.addEventListener('input', () => {
    if (Number.isFinite(video.duration) && video.duration > 0) {
      video.currentTime = Number(seek.value) / 100 * video.duration;
      progress();
    }
  });
  if (!root.requestFullscreen && !video.webkitEnterFullscreen) fullscreenButton.hidden = true;
  fullscreenButton.addEventListener('click', async () => {
    try {
      if (document.fullscreenElement) await document.exitFullscreen();
      else if (root.requestFullscreen) await root.requestFullscreen();
      else video.webkitEnterFullscreen?.();
    } catch { /* Inline playback remains available. */ }
  });
  document.addEventListener('fullscreenchange', () => {
    fullscreenButton.setAttribute('aria-label', document.fullscreenElement ? 'Salir de pantalla completa' : 'Ver en pantalla completa');
  });
  ['play', 'playing', 'pause', 'volumechange', 'ended'].forEach(event => video.addEventListener(event, sync));
  ['timeupdate', 'durationchange', 'loadedmetadata'].forEach(event => video.addEventListener(event, progress));
  function fail() {
    if (failed) return;
    failed = true;
    video.pause();
    controls.hidden = true;
    status.hidden = false;
    status.textContent = 'No se pudo reproducir el video. ';
    const link = document.createElement('a');
    link.href = video.querySelector('source').src;
    link.textContent = 'Abrir video';
    link.target = '_blank';
    link.rel = 'noopener noreferrer';
    status.append(link);
  }
  video.addEventListener('error', fail);
  video.querySelector('source').addEventListener('error', fail);
  if ('IntersectionObserver' in window) {
    new IntersectionObserver(entries => { visible = entries[0].isIntersecting; automatic(); }, {threshold: .25}).observe(root);
  } else { visible = true; automatic(); }
  document.addEventListener('visibilitychange', automatic);
  reduced.addEventListener('change', automatic);
  sync();
})();


/* ===== PARALLAX Y ANIMACIONES ACCESIBLES ===== */
(() => {
  'use strict';
  const reduced = matchMedia('(prefers-reduced-motion: reduce)');
  const header = document.querySelector('.site-header');
  const hero = document.querySelector('.welcome-hero');
  let frame = 0, revealObserver;
  const targets = [];
  const active = new Set();
  function register(selector, strength) {
    document.querySelectorAll(selector).forEach(media => {
      media.classList.add('parallax-image');
      targets.push({media, container: media.parentElement, strength});
    });
  }
  register('.inner-banner-media img', 20);
  register('.compact-card-media img,.service-overview-image img', 9);
  register('.about-photo img', 10);
  register('.about-story>img,.station-service>img', 8);
  register('.carousel:not(.product-gallery) .slide img', 7);
  register('.product-image img', 4);
  register('.concept-image img', 10);
  register('.film-player video', 5);
  function paint() {
    frame = 0;
    header?.classList.toggle('is-scrolled', window.scrollY > 20);
    const disabled = reduced.matches || !!navigator.connection?.saveData;
    const height = window.innerHeight || 800;
    const mobile = window.innerWidth <= 600;
    if (hero) {
      const r = hero.getBoundingClientRect();
      const shift = disabled ? 0 : Math.min(mobile ? 10 : 24, Math.max(0, -r.top) * (mobile ? .035 : .065));
      hero.style.setProperty('--hero-shift', `${shift.toFixed(1)}px`);
    }
    for (const item of targets) {
      if (disabled) { item.media.style.setProperty('--parallax-y', '0px'); continue; }
      if (!active.has(item.container)) continue;
      const r = item.container.getBoundingClientRect();
      const progress = Math.max(-1, Math.min(1, (height / 2 - (r.top + r.height / 2)) / ((height + r.height) / 2)));
      const shift = progress * item.strength * (mobile ? .45 : 1);
      item.media.style.setProperty('--parallax-y', `${shift.toFixed(2)}px`);
    }
  }
  function request() { if (!frame) frame = requestAnimationFrame(paint); }
  document.querySelectorAll('.page-inner .section-head,.page-inner .project-heading,.page-inner .about-story,.page-inner .station-service,.page-inner .service-row,.page-inner .contact-grid>div,.service-application').forEach(el => el.dataset.reveal = '');
  const items = [...document.querySelectorAll('[data-reveal]')];
  function reveal() {
    revealObserver?.disconnect();
    if (reduced.matches || !('IntersectionObserver' in window)) {
      document.documentElement.classList.remove('motion-ready');
      items.forEach(el => el.classList.add('is-visible'));
      return;
    }
    document.documentElement.classList.add('motion-ready');
    revealObserver = new IntersectionObserver(entries => {
      entries.forEach(entry => {
        if (entry.isIntersecting) {
          entry.target.classList.add('is-visible');
          revealObserver.unobserve(entry.target);
        }
      });
    }, {threshold: .08, rootMargin: '0px 0px -25px 0px'});
    items.filter(el => !el.classList.contains('is-visible')).forEach(el => revealObserver.observe(el));
  }
  reveal();
  if ('IntersectionObserver' in window) {
    const visibility = new IntersectionObserver(entries => {
      entries.forEach(entry => entry.isIntersecting ? active.add(entry.target) : active.delete(entry.target));
      request();
    }, {rootMargin: '80px'});
    new Set(targets.map(item => item.container)).forEach(container => visibility.observe(container));
  } else targets.forEach(item => active.add(item.container));
  reduced.addEventListener('change', () => { reveal(); request(); });
  window.addEventListener('scroll', request, {passive: true});
  window.addEventListener('resize', request, {passive: true});
  document.addEventListener('focusin', event => event.target.closest('[data-reveal]')?.classList.add('is-visible'));
  request();
})();

